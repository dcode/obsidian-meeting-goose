/**
 * Regenerates THIRD-PARTY-NOTICES.md from what esbuild actually bundles into
 * main.js. Run `npm run notices` after adding, removing, or upgrading a
 * runtime dependency.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import builtins from 'builtin-modules';
import esbuild from 'esbuild';

const OUTPUT = 'THIRD-PARTY-NOTICES.md';

const { metafile } = await esbuild.build({
  entryPoints: ['src/main.ts'],
  bundle: true,
  write: false,
  metafile: true,
  format: 'cjs',
  external: ['obsidian', 'electron', ...builtins, ...builtins.map((name) => `node:${name}`)],
  logLevel: 'silent',
});

const packageDirs = new Set();
for (const input of Object.keys(metafile.inputs)) {
  const match = input.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//);
  if (match) packageDirs.add(match[1]);
}

const packages = [...packageDirs]
  .map((dir) => {
    const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    const licenseFiles = readdirSync(dir)
      .filter((file) => /^(licen[sc]e|notice)/i.test(file))
      .sort();
    if (licenseFiles.length === 0) {
      throw new Error(`${pkg.name} ships no license file; add its notice by hand`);
    }
    const repository = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
    return {
      name: pkg.name,
      version: pkg.version,
      license: pkg.license,
      homepage: pkg.homepage ?? repository?.replace(/^git\+/, '').replace(/\.git$/, ''),
      texts: licenseFiles.map((file) => readFileSync(join(dir, file), 'utf8').trim()),
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const lines = [
  '# Third-party notices',
  '',
  'The released `main.js` bundles the packages below. Each is redistributed',
  'under its own license, reproduced here in full.',
  '',
  'Generated by `npm run notices` — do not edit by hand.',
  '',
  '| Package | Version | License |',
  '|---------|---------|---------|',
  ...packages.map((pkg) => `| ${pkg.name} | ${pkg.version} | ${pkg.license} |`),
  '',
];

for (const pkg of packages) {
  lines.push(`## ${pkg.name} ${pkg.version}`, '', `License: ${pkg.license}`);
  if (pkg.homepage) lines.push(`Source: ${pkg.homepage}`);
  for (const text of pkg.texts) {
    lines.push('', '```text', text, '```');
  }
  lines.push('');
}

writeFileSync(OUTPUT, lines.join('\n'));
console.log(`Wrote ${OUTPUT} (${packages.length} packages)`);
